"""Merges the 12 spec styles with scripts/extra_styles.json and writes both
 - supabase/functions/_shared/catalog.ts   (server prompts)
 - the marked block inside web/index.html  (client tiles, wall chips, demo-mode tint)
Run:  python3 -I scripts/build_styles.py ../deconova-build-spec.md      (from the mvp folder)
Wall chips for the extra styles are derived from the 4 palette colours: the colour itself, a pale and a deep version."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
spec = pathlib.Path(sys.argv[1]).read_text()
base = json.loads(re.search(r'```json\n(.*?)\n```', spec.split('## 14.')[1], re.S).group(1))
extra = json.loads((root/'scripts/extra_styles.json').read_text())

def mix(a, b, t):
    A = [int(a[i:i+2], 16) for i in (1,3,5)]; B = [int(b[i:i+2], 16) for i in (1,3,5)]
    return '#%02X%02X%02X' % tuple(round(x*(1-t)+y*t) for x, y in zip(A, B))
for s in extra:
    s['chips'] = []
    for n, h in s['palette']:
        s['chips'] += [[n, h], ['Pale '+n.lower(), mix(h, '#F4F0E8', .6)], ['Deep '+n.lower(), mix(h, '#2A2622', .35)]]
    assert len(s['chips']) == 12 and len({s2['id'] for s2 in base+extra}) == len(base+extra)

# packs from spec section 2
packs = {}
for line in spec.split('## 2.')[1].split('## 3.')[0].splitlines():
    m = re.match(r'\|\s*`(\w+)`\s*\|\s*([^|]+)\|\s*([^|]+)\|', line)
    if m: packs[m.group(1)] = {'label': m.group(2).strip(), 'constraints': m.group(3).strip()}
keys = ('id','label','palette','materials','lighting','prompt_dna')
allst = [{k: s[k] for k in keys} for s in base + extra]
(root/'supabase/functions/_shared/catalog.ts').write_text(
  '// GENERATED by scripts/build_styles.py. Do not edit.\n'
  f'export const STYLES: any[] = {json.dumps(allst, indent=1)};\n'
  f'export const PACKS: Record<string, {{label:string; constraints:string}}> = {json.dumps(packs, indent=1)};\n')

def js(s):
    q = lambda x: json.dumps(x, ensure_ascii=False).replace('"', "'") if False else json.dumps(x, ensure_ascii=False)
    return ("  {id:%s,label:%s,group:%s,\n   palette:%s,\n   fx:%s,\n   chips:%s}" %
            (q(s['id']), q(s['label']), q(s['group']), q(s['palette']), q(s['fx']), q(s['chips'])))
block = '/*EXTRA_STYLES_START*/\n' + ',\n'.join(js(s) for s in extra) + '\n/*EXTRA_STYLES_END*/'
p = root/'web/index.html'; t = p.read_text(encoding='utf-8')
if '/*EXTRA_STYLES_START*/' in t:
    t = re.sub(r'/\*EXTRA_STYLES_START\*/.*?/\*EXTRA_STYLES_END\*/', lambda m: block, t, flags=re.S)
else:
    i = t.index("  {id:'south_indian'"); j = t.index('\n];', i)
    t = t[:j].rstrip() + ',\n' + block + t[j:]
p.write_text(t, encoding='utf-8')
print(len(base), '+', len(extra), '=', len(allst), 'styles;', len(packs), 'packs')
